function readPath(source, path) {
  return path.split('.').reduce((value, key) => value?.[key], source);
}

export function translate(language, key, replacements = {}) {
  const resolvedLanguage = normalizeLanguage(language);
  const fallback = readPath(TRANSLATIONS[DEFAULT_LANGUAGE], key) ?? key;
  const template = readPath(TRANSLATIONS[resolvedLanguage], key) ?? fallback;

  return String(template).replace(/\{(\w+)\}/g, (_, token) => (
    replacements[token] !== undefined ? String(replacements[token]) : `{${token}}`
  ));
}

